export const REL = {
  因果: "対象の文は、前に書かれたことを理由・原因として、その結果や判断を述べる(だから・そのため・したがって)",
  逆接: "対象の文は、前に書かれたことから予想されることと逆か、前に反することを述べる(しかし・それでも・ところが)",
  言い換え:
    "対象の文は、前に書かれたことを言い換える・まとめる(つまり・要するに)",
  添加: "対象の文は、前と同じ向きのことを並べる・付け足す(また・さらに・しかも)",
  対比: "対象の文は、前と別の面や反対の面を比べて述べる(一方で・逆に)",
  例示: "対象の文は、前に書かれたことの例を挙げる(例えば)",
  補足: "対象の文は、前に書かれたことに補足・ただし書き・例外を付ける(なお・ただし・特に)",
  理由: "対象の文は、前に書かれたことの理由を後から述べる(なぜなら・というのも)",
  順序: "対象の文は、前のことの後に起きたこと・次の手順を述べる(その後・それから・すると)",
  転換: "対象の文は、話題を変える(ところで・さて)",
  無し: "つなぎの言葉を入れずに続けるのが自然",
} as const;
export type Rel = keyof typeof REL;

const WORDS: [string, Rel[]][] = (
  [
    [
      "だから,ですから,それで,そのため,そのために,このため,したがって,よって,ゆえに,その結果,結果として,こうして,なので",
      ["因果"],
    ],
    [
      "しかし,しかしながら,だが,でも,けれども,けれど,ところが,それでも,とはいえ,それなのに,なのに,にもかかわらず",
      ["逆接"],
    ],
    ["つまり,要するに,すなわち,いわば,言い換えると,言い換えれば", ["言い換え"]],
    [
      "また,さらに,しかも,そのうえ,それに,加えて,あわせて,あるいは,または,もしくは",
      ["添加"],
    ],
    ["一方,一方で,反対に,逆に,その代わり,そのかわり,代わりに,むしろ", ["対比"]],
    ["例えば,たとえば", ["例示"]],
    ["なお,ちなみに,ただし,もっとも,特に,とくに,中でも,実際,実は", ["補足"]],
    ["なぜなら,というのも", ["理由"]],
    ["まず,次に,最後に,そのあと,その後,それから,すると,やがて", ["順序"]],
    ["ところで,さて", ["転換"]],
    ["ただ", ["逆接", "補足"]],
    ["そこで", ["因果", "順序"]],
    ["そして", ["添加", "順序"]],
  ] as [string, Rel[]][]
)
  .flatMap(([ws, r]) => ws.split(",").map((w) => [w, r] as [string, Rel[]]))
  .sort((a, b) => b[0].length - a[0].length);

/** 文頭の接続詞と、それが表す関係と、接続詞(と続く「、」)を除いた残り。docs/design/cli.md「接続詞を見る」参照 */
export function headWord(
  s: string,
): { word: string; rels: Rel[]; rest: string } | null {
  for (const [w, rels] of WORDS) {
    if (!s.startsWith(w)) continue;
    const c = s[w.length] ?? "";
    if (w === "実は" && s[w.length + 1] === "の") continue;
    if (c === "、" || !"のにはがをもでと".includes(c))
      return { word: w, rels, rest: s.slice(w.length).replace(/^、/, "") };
  }
  return null;
}
